# Writes src/data/cie-tables.ts from RIT's all_1nm_data.xls: D65 multiplied by the CIE 1931 2 degree observer,
# 380 to 730 nm at 10 nm, normalised so a perfect reflector gives Y = 1.
#
# Run by hand when the tables need rebuilding. It needs the xlrd package, and the workbook comes from
# rit-mcsl.org/UsefulData/.
# Usage: python -X utf8 scripts/build-colour-tables.py <path to all_1nm_data.xls>
import os
import sys

import xlrd

WAVELENGTHS = range(380, 731, 10)
D65_COLUMN = 2
OBSERVER_COLUMNS = (5, 6, 7)
FIRST_DATA_ROW = 4
OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'cie-tables.ts')

# Values printed in CIE 15 and CIE 191, used to catch a shifted column or a bad copy of the workbook.
PUBLISHED_D65 = {380: 49.9755, 560: 100.0, 700: 71.6091}
PUBLISHED_OBSERVER = {380: (.0014, .0000, .0065), 560: (.5945, .9950, .0039), 700: (.0114, .0041, .0000)}
PUBLISHED_TOLERANCE = 5e-4


# Reads the workbook into a row per whole wavelength.
def read_rows(path):
    sheet = xlrd.open_workbook(path).sheet_by_index(0)
    return {int(sheet.cell_value(r, 0)): sheet.row_values(r) for r in range(FIRST_DATA_ROW, sheet.nrows) if sheet.cell_value(r, 0) != ''}


# Stops the build if the workbook disagrees with the published standards.
def check_against_published(rows):
    for nm, expected in PUBLISHED_D65.items():
        assert abs(rows[nm][D65_COLUMN] - expected) < PUBLISHED_TOLERANCE, (nm, rows[nm][D65_COLUMN])
    for nm, expected in PUBLISHED_OBSERVER.items():
        found = [rows[nm][c] or 0 for c in OBSERVER_COLUMNS]
        assert all(abs(a - b) < PUBLISHED_TOLERANCE for a, b in zip(found, expected)), (nm, found)


# Multiplies the illuminant by the observer and scales the result so Y sums to one.
def build_weights(rows):
    weights = [[rows[nm][D65_COLUMN] * (rows[nm][c] or 0) for c in OBSERVER_COLUMNS] for nm in WAVELENGTHS]
    total = sum(w[1] for w in weights)
    return [[v / total for v in w] for w in weights]


# Formats one named table as a TypeScript constant.
def table(name, comment, values):
    body = ', '.join(repr(v) for v in values)
    return f'// {comment}\nexport const {name}: readonly number[] = [{body}];\n'


rows = read_rows(sys.argv[1])
check_against_published(rows)
weights = build_weights(rows)
text = '\n'.join([
    '// Developed by Interactive 63 (https://interactive63.com)\n//\n'
    '// CIE weighting tables for turning a reflectance curve into XYZ. Generated by scripts/build-colour-tables.py: do not edit by hand.\n',
    table('WAVELENGTHS', 'Sample points in nanometres, shared by every reflectance, K and S curve.', list(WAVELENGTHS)),
    table('WEIGHT_X', 'D65 multiplied by the 2 degree x-bar function, on the same scale as WEIGHT_Y.', [w[0] for w in weights]),
    table('WEIGHT_Y', 'D65 multiplied by the 2 degree y-bar function, summing to one.', [w[1] for w in weights]),
    table('WEIGHT_Z', 'D65 multiplied by the 2 degree z-bar function, on the same scale as WEIGHT_Y.', [w[2] for w in weights]),
])
with open(OUTPUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write(text)
print('white point', [round(sum(w[i] for w in weights), 5) for i in range(3)])
